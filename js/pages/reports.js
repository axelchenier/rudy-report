// reports.js - the Reports tab: Daily, Weekly and Monthly reports made by pipeline/update_reports.py.
// Each report is a JSON file in data/reports/. This page only DISPLAYS them; all numbers come from those files.
import { esc } from "../ui.js";

const KINDS = { daily: "Daily", weekly: "Weekly", monthly: "Monthly" };
const cache = new Map();
const getJSON = (path) => { if (!cache.has(path)) cache.set(path, fetch(path).then((r) => { if (!r.ok) throw new Error(`Could not load ${path}`); return r.json(); })); return cache.get(path); };

// ---------- little formatting helpers ----------
const pct = (v) => v == null ? "–" : (v * 100).toFixed(1) + "%";
const num = (v, d = 1) => v == null ? "–" : Number(v).toFixed(d);
const signed = (v, d = 1) => v == null ? "–" : (v > 0 ? "+" : "") + Number(v).toFixed(d);
const day = (iso) => new Date(iso + "T12:00:00").toLocaleDateString("en-US", { month: "short", day: "numeric", year: "numeric" });
const pl = (x) => `<a href="#/player/${x.player_id}">${esc(x.player)}</a> <span class="muted small">${esc(x.team || "")}</span>`;
const tm = (x) => `<a href="#/team/${x.team_id}">${esc(x.team)}</a>`;

// A change with an arrow and color. asPct: the value is a fraction (0.012 -> +1.2 pts). lowerBetter flips colors.
function delta(v, { d = 1, asPct = false, lowerBetter = false } = {}) {
  if (v == null) return `<span class="muted">–</span>`;
  const shown = asPct ? (v * 100).toFixed(1) : Number(v).toFixed(d);
  if (Number(shown) === 0) return `<span class="delta flat">● 0</span>`;
  const up = v > 0, good = lowerBetter ? !up : up;
  return `<span class="delta ${good ? "up" : "down"}">${up ? "▲" : "▼"} ${up ? "+" : ""}${shown}</span>`;
}

// Simple table from rows + [header, cell-function] pairs.
function table(rows, cols, empty = "Nothing to show yet.") {
  if (!rows?.length) return `<p class="muted small">${empty}</p>`;
  return `<div class="table-wrap"><table class="data"><thead><tr>${cols.map(([h, , left]) => `<th class="${left ? "left" : ""}" style="cursor:default">${h}</th>`).join("")}</tr></thead>
    <tbody>${rows.map((r) => `<tr>${cols.map(([, f, left]) => `<td class="${left ? "left" : ""}">${f(r)}</td>`).join("")}</tr>`).join("")}</tbody></table></div>`;
}
const section = (title, body, sub = "") => `<section class="report-section"><h2>${title}</h2>${sub ? `<p class="muted small">${sub}</p>` : ""}${body}</section>`;

export async function reportsPage(app, kind = "daily", name = "") {
  kind = KINDS[kind] ? kind : "daily";
  let index;
  try { index = await getJSON("data/reports/index.json"); }
  catch { app.innerHTML = `<h1>Reports</h1><p class="muted">No reports yet. Run <code>.venv/bin/python pipeline/update_reports.py</code>.</p>`; return; }
  const list = index[kind] || [];
  const item = list.find((i) => i.name === name) || list[0];

  app.innerHTML = `
    <div class="page-head"><div><h1>Reports</h1><p class="sub">What happened in the NBA, built only from NBA.com box scores. No predictions.</p></div>
      <div class="toolbar" style="margin:0">
        <div class="tabs">${Object.entries(KINDS).map(([k, l]) => `<a class="tab-link ${k === kind ? "active" : ""}" href="#/reports/${k}">${l}</a>`).join("")}</div>
        <label>Report <select id="pick">${list.map((i) => `<option value="${esc(i.name)}" ${i === item ? "selected" : ""}>${i.name === "latest" ? "Latest (rolling)" : esc(day(i.end))} · ${i.games} games</option>`).join("")}</select></label>
      </div></div>
    <div id="report">${item ? "<p class='muted'>Loading…</p>" : `<p class="muted">No ${kind} reports yet.</p>`}</div>`;
  app.querySelector("#pick").addEventListener("change", (e) => { location.hash = `#/reports/${kind}/${e.target.value}`; });
  if (!item) return;
  const rep = await getJSON(`data/reports/${item.file}`);
  app.querySelector("#report").innerHTML = render(rep);
}

function render(rep) {
  const k = rep.type, wc = rep.what_changed;
  const range = rep.range.start === rep.range.end ? day(rep.range.end) : `${day(rep.range.start)} – ${day(rep.range.end)}`;
  let html = `
    <div class="card report-head">
      <h2 style="margin:0">${esc(rep.title)}</h2>
      <p class="muted small" style="margin:4px 0 0">Covers <b>${range}</b> · ${rep.summary.games} games · ${rep.season} season ·
        generated ${esc(rep.generated_at)} · Source: ${rep.sources.map(esc).join("; ")}</p>
      ${rep.notes.length ? `<div class="callout">${rep.notes.map((n) => `<p>⚠ ${esc(n)}</p>`).join("")}</div>` : ""}
    </div>`;

  html += section("Interesting trends", rep.trends.length ? `<ul class="trends">${rep.trends.map((t) => `<li>${esc(t)}</li>`).join("")}</ul>` : `<p class="muted">No trends yet.</p>`,
    "Every sentence is generated by rules from the numbers below.");

  // ---------- Daily: scores, top performers, notable lines ----------
  if (k === "daily") {
    html += section("Scores", `<div class="scores">${rep.games.map((g) => {
      const homeWon = g.home_pts > g.away_pts;
      return `<div class="card score"><div class="${homeWon ? "" : "win"}"><a href="#/team/${g.away_id}">${esc(g.away_abbr)}</a><b>${g.away_pts}</b></div>
        <div class="${homeWon ? "win" : ""}"><a href="#/team/${g.home_id}">${esc(g.home_abbr)}</a><b>${g.home_pts}</b></div>
        <div class="muted small">${g.ot ? `Final/${g.ot > 1 ? g.ot : ""}OT` : "Final"} · ${esc(g.away)} @ ${esc(g.home)}</div></div>`;
    }).join("")}</div>`);
  }
  html += section(k === "daily" ? "Top performers" : "Best single games", table(rep.top_performers, [
    ["Player", pl, true], ["Date", (r) => esc(day(r.date)), true], ["Opp", (r) => esc(r.opp) + ` <span class="muted small">${r.wl}</span>`, true],
    ["Line", (r) => esc(r.line), true], ["Game Score", (r) => `<b>${num(r.gmsc)}</b>`]]), "Ranked by Game Score, a one-number summary of a box-score line.");
  const nc = rep.notable_counts;
  html += section("Notable stat lines", table(rep.notable, [["Player", pl, true], ["Date", (r) => esc(day(r.date)), true],
    ["What", (r) => r.tags.map((t) => `<span class="tag">${esc(t)}</span>`).join(" "), true], ["Line", (r) => esc(r.line), true]], "No 30-point games, triple-doubles, 20-20s or 5-three games."),
    `${nc["30_point_games"]} 30-point games · ${nc.triple_doubles} triple-doubles · ${nc.twenty_twenty} 20-20s · ${nc.games_5_threes} games with 5+ threes`);
  html += section("Standout team performances", `<div class="grid stat-cards">${rep.team_standouts.map((s) =>
    `<div class="card stat-card"><div class="label">${esc(s.label)}</div><div class="value">${esc(s.value)}</div>
      <div class="rank">${tm(s)} ${esc(s.detail)}${k !== "daily" ? ` · ${esc(day(s.date))}` : ""}</div></div>`).join("")}</div>`);

  // ---------- Weekly / monthly: leaders ----------
  if (rep.leaders.length) {
    html += section("Leaders this period", `<div class="leader-grid">${rep.leaders.map((L) => `<div class="card"><h3>${esc(L.label)}</h3>
      ${table(L.rows, [["", pl, true], ["G", (r) => r.gp], ["", (r) => `<b>${L.stat === "TS_PCT" ? pct(r.value) : num(r.value)}</b>`]])}</div>`).join("")}</div>`, esc(rep.qualifier));
  }

  // ---------- What changed ----------
  html += `<section class="report-section"><h2>What changed <span class="muted small">${esc(wc.label)}</span></h2>
    ${wc.note ? `<div class="callout"><p>ℹ ${esc(wc.note)}</p></div>` : ""}
    <div class="grid two-col">
      <div class="card"><h3>League-wide averages</h3>${table(wc.league, [["", (r) => esc(r.label), true],
        ["Now", (r) => r.stat.endsWith("PCT") ? pct(r.current) : num(r.current)], [wc.basis === "last_season" ? "Last season" : "Before", (r) => r.stat.endsWith("PCT") ? pct(r.prior) : num(r.prior)],
        ["Change", (r) => delta(r.delta, { asPct: r.stat.endsWith("PCT") })]])}</div>
      <div class="card"><h3>Leader changes</h3><p class="muted small">${esc(wc.leaders_note || "")}</p>${table(wc.leaders, [["", (r) => esc(r.label), true],
        ["Now", (r) => `${r.current.player_id ? pl(r.current) : tm(r.current)} <b>${r.stat === "TS_PCT" ? pct(r.current.value) : r.stat === "NET" ? signed(r.current.value) : num(r.current.value)}</b>`, true],
        ["Before", (r) => r.prior ? `${r.prior.player_id ? pl(r.prior) : tm(r.prior)} ${r.stat === "TS_PCT" ? pct(r.prior.value) : r.stat === "NET" ? signed(r.prior.value) : num(r.prior.value)}` : "–", true],
        ["", (r) => r.changed ? `<span class="tag new">new leader</span>` : ""]])}</div>
    </div>
    <div class="grid two-col">
      <div class="card"><h3>Biggest risers · points per game</h3>${table(wc.ppg_risers.filter((r) => r.ppg_delta > 0), changeCols("ppg"), "No players qualified in both periods.")}</div>
      <div class="card"><h3>Biggest fallers · points per game</h3>${table(wc.ppg_fallers.filter((r) => r.ppg_delta < 0), changeCols("ppg"), "No players qualified in both periods.")}</div>
      <div class="card"><h3>True shooting % · risers</h3>${table(wc.ts_risers.filter((r) => r.ts_delta > 0), changeCols("ts"), "No players qualified in both periods.")}</div>
      <div class="card"><h3>True shooting % · fallers</h3>${table(wc.ts_fallers.filter((r) => r.ts_delta < 0), changeCols("ts"), "No players qualified in both periods.")}</div>
    </div>
    <p class="muted small">${wc.players_compared} players met the minimums in both periods. ${esc(rep.qualifier)}${wc.basis === "last_season" ? " Last-season side: 20+ games, 15+ min/game." : ""}</p>
    <div class="card" style="margin-top:12px"><h3>Teams: record and net rating change</h3>${table(wc.teams, [["Team", tm, true],
      ["Record", (r) => r.record], [wc.basis === "last_season" ? "Last season" : "Before", (r) => r.prior_record],
      ["Net rtg", (r) => signed(r.net)], ["Before", (r) => signed(r.prior_net)], ["Net change", (r) => delta(r.net_delta)],
      ["Pace", (r) => num(r.pace)], ["Pace chg", (r) => delta(r.pace - r.prior_pace)], ["3PA/100", (r) => num(r.fg3a100)], ["3PA/100 chg", (r) => delta(r.fg3a100 - r.prior_fg3a100)]],
      "No team played in both periods.")}</div>
  </section>`;

  // ---------- Hot / cold vs last season ----------
  const hcCols = [["Player", pl, true], ["G", (r) => r.gp], ["MIN", (r) => num(r.min)], ["PPG", (r) => `<b>${num(r.ppg)}</b>`],
    ["Last season", (r) => num(r.prior_ppg)], ["Change", (r) => delta(r.delta)], ["TS%", (r) => pct(r.ts)], ["Last TS%", (r) => pct(r.prior_ts)]];
  html += section("Hottest and coldest vs last season", `<div class="grid two-col"><div class="card"><h3>🔥 Hottest</h3>${table(rep.hot.filter((r) => r.delta > 0), hcCols)}</div>
    <div class="card"><h3>🧊 Coldest</h3>${table(rep.cold.filter((r) => r.delta < 0), hcCols)}</div></div>`, esc(rep.hot_cold_basis));

  // ---------- Teams, streaks, rookies, efficiency ----------
  if (k !== "daily") {
    html += section("Team trends", table(rep.teams, [["Team", tm, true], ["G", (r) => r.gp], ["W-L", (r) => `${r.w}-${r.l}`], ["Net", (r) => signed(r.net)],
      ["vs last season", (r) => delta(r.last_net == null ? null : r.net - r.last_net)], ["ORtg", (r) => num(r.ortg)], ["DRtg", (r) => num(r.drtg)],
      ["Pace", (r) => num(r.pace)], ["Pace chg", (r) => delta(r.last_pace == null ? null : r.pace - r.last_pace)],
      ["3PA/100", (r) => num(r.fg3a100)], ["3PA/100 chg", (r) => delta(r.last_fg3a100 == null ? null : r.fg3a100 - r.last_fg3a100)],
      ["Last season W-L", (r) => r.last_record || "–"]]), esc(rep.teams_basis) + " Ratings are per 100 possessions estimated from box scores.");
  }
  html += `<div class="grid two-col">
    ${section("Win / loss streaks", table(rep.streaks, [["Team", tm, true], ["Streak", (r) => `<span class="delta ${r.type === "W" ? "up" : "down"}">${r.type}${r.n}</span>`], ["Season games", (r) => r.games]], "No streaks of 2+ games yet."), "Current streaks as of the report's last day.")}
    ${section("Rookies", table(rep.rookies, [["Rookie", pl, true], ["G", (r) => r.gp], ["MIN", (r) => num(r.min)], ["PTS", (r) => `<b>${num(r.ppg)}</b>`], ["REB", (r) => num(r.rpg)], ["AST", (r) => num(r.apg)], ["TS%", (r) => pct(r.ts)]], "No rookies met the minimums."), "First-year players (NBA.com), same minimums as above.")}
  </div>`;
  const e = rep.efficiency;
  const effCols = [["Player", pl, true], ["G", (r) => r.gp], ["PPG", (r) => num(r.ppg)], ["TS%", (r) => `<b>${pct(r.ts)}</b>`], ["vs league", (r) => delta(e.league_ts == null ? null : r.ts - e.league_ts, { asPct: true })]];
  html += section("Efficiency outliers", `<div class="grid two-col"><div class="card"><h3>Most efficient volume scorers</h3>${table(e.high, effCols)}</div>
    <div class="card"><h3>Least efficient volume scorers</h3>${table(e.low, effCols)}</div></div>`, `${esc(e.rule)}. League true shooting in this period: ${pct(e.league_ts)}.`);
  return html;
}

function changeCols(which) {
  return which === "ppg"
    ? [["Player", pl, true], ["G", (r) => `${r.gp} / ${r.prior_gp}`], ["PPG", (r) => `<b>${num(r.ppg)}</b>`], ["Before", (r) => num(r.prior_ppg)], ["Change", (r) => delta(r.ppg_delta)]]
    : [["Player", pl, true], ["G", (r) => `${r.gp} / ${r.prior_gp}`], ["TS%", (r) => `<b>${pct(r.ts)}</b>`], ["Before", (r) => pct(r.prior_ts)], ["Change", (r) => delta(r.ts_delta, { asPct: true })]];
}
