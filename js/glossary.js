// Tooltip text for a stat code: "Full name: definition (formula)".
export function tip(key) {
  const g = GLOSSARY[key], s = STATS[key];
  if (!g && !s) return "";
  const name = s?.name ? s.name[0].toUpperCase() + s.name.slice(1) : key;
  return `${name}${g ? `: ${g[1]}` : ""}${g?.[2] ? `  Formula: ${g[2]}` : ""}${s?.lowerBetter ? "  (Lower is better.)" : ""}`;
}
